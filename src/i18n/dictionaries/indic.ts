/**
 * Helper to build derived Indic language dictionaries by deep-merging specific overrides
 * over a foundational Indic structure with English fallback safety.
 */
function createDictionary(overrides: Partial<Record<keyof TranslationDictionary, any>>): TranslationDictionary {
  const result = JSON.parse(JSON.stringify(hi)) as TranslationDictionary;
  for (const [sectionKey, sectionValues] of Object.entries(overrides)) {
    if (result[sectionKey as keyof TranslationDictionary] && typeof sectionValues === 'object') {
      Object.assign(result[sectionKey as keyof TranslationDictionary], sectionValues);
    }
  }
  return result;
}

